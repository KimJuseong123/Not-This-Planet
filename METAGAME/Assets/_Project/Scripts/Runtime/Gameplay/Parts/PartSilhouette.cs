        public const int Bands = 40;

        /// <summary><see cref="PartSpec.Name"/> 과 같다.</summary>
        public readonly string PartName;

        /// <summary>
        /// 구간별 왼쪽 끝. 바닥이 0번이다. <b>가장 넓은 폭을 1 로 정규화</b>했고
        /// 부호는 모델 원점 기준이므로, 좌우로 치우친 파츠는 그 치우침이 남는다.
        /// </summary>
        public readonly float[] Left;

        /// <summary>구간별 오른쪽 끝. <see cref="Left"/> 와 같은 단위다.</summary>
        public readonly float[] Right;

        PartSilhouette(string partName, float[] left, float[] right)
        {
            PartName = partName;
            Left = left;
            Right = right;
        }

        /// <summary>가장 넓은 구간의 폭. 정규화했으므로 1 이다.</summary>
        public float NormalizedWidth
        {
            get
            {
                var widest = 0f;
                for (var i = 0; i < Bands; i++) widest = Mathf.Max(widest, Right[i] - Left[i]);
                return widest;
            }
        }

        /// <summary>이름으로 찾는다. 없으면 null 이다.</summary>
        public static PartSilhouette Find(string partName)
        {
            for (var i = 0; i < All.Length; i++)
                if (All[i].PartName == partName)
                    return All[i];

            return null;
        }

