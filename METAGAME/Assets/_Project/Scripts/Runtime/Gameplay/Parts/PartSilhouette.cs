    /// <b>가로로 떨어진 두 덩어리는 표현하지 못한다.</b> 구간마다 좌우 끝 하나씩만
    /// 갖고 있으므로, 같은 높이에 날개가 둘이면 사이가 메워진 하나로 그려진다.
    /// 실루엣이라 그것으로 족하다.
