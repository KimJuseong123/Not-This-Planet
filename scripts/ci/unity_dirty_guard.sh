#!/usr/bin/env sh
# 배치모드 빌드가 **추적되는 에셋을 지웠는지** 본다 (S15P21B202-351 · S15P21B202-532).
#
# 실행: sh scripts/ci/unity_dirty_guard.sh
# 지운 것이 있으면 목록을 찍고 1, 없으면 0. 재직렬화 건수는 항상 한 줄로 알린다.
#
# ── 무엇이 위험한가 ────────────────────────────────────────────────────
# 배치모드 빌드는 임포트 과정에서 에셋을 **재직렬화**하고, 에디터 스크립트가 에셋을
# **지우기도 한다** — `ArtLink.CleanStale` 이 실제로 `PF_Stage1_Tablet.prefab` 을 매
# 빌드 지웠다. 그러면 그 에셋이 빠진 플레이어가 빌드되는데, `Resources` 아래는
# `Resources.Load` 로만 쓰여 컴파일 검사에 안 걸리고, CI 워크스페이스는 매번
# `git clean` 되므로 **삭제가 커밋되지 않아 흔적도 안 남는다.** 종료 코드는 0이다.
#
# **삭제(D)만 막는다. 재직렬화(M)는 정상이다** — 차가운 Library 에서는 늘 생긴다.
#
# ── 왜 파일로 떼었나 (S15P21B202-532) ──────────────────────────────────
# 릴리스와 개발 빌드가 **같은 위험을 다르게 판정하고 있었다.** 릴리스는 삭제만 봤고,
# 개발 빌드는 `git diff --quiet` 로 바뀌기만 하면 실패했다. 배치모드는 늘 재직렬화하므로
# 개발 빌드는 **성공할 수가 없었고**, 2026-09-15 첫 새벽 실행부터 죽었다
# (재직렬화 20건 · 삭제 0건 · 빌드 자체는 444.5MB 로 성공).
#
# 생각을 복사하면 이렇게 갈라진다. 그래서 판정을 한 곳에 두고 양쪽이 부른다.
set -u

DELETED=$(git status --porcelain -- METAGAME/ | grep -E "^(.?D|D.?) " || true)
RESERIALIZED=$(git status --porcelain -- METAGAME/ | grep -Ec "^(.?M|M.?) " || true)

echo "빌드 뒤 METAGAME/ — 재직렬화 ${RESERIALIZED}건"

if [ -n "$DELETED" ]; then
  echo "❌ 빌드가 추적되는 에셋을 삭제했다 — 그 에셋 없이 만들어진 빌드다 (S15P21B202-351)"
  echo "$DELETED"
  exit 1
fi

echo "✅ 삭제된 에셋 없음"
exit 0
